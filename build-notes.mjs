import { readdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("./", import.meta.url);
const files = (await readdir(root))
  .filter((file) => /^\d{2}-.+\.md$/i.test(file) || /^README\.md$/i.test(file))
  .sort((a, b) => {
    const partOf = (file) => (/^README\.md$/i.test(file) ? 0 : Number(file.match(/^(\d+)/)[1]));
    return partOf(a) - partOf(b);
  });

const notes = [];

for (const file of files) {
  const content = await readFile(new URL(file, root), "utf8");
  const overview = /^README\.md$/i.test(file);
  const part = overview ? 0 : Number(file.match(/^(\d+)/)[1]);
  const heading = content.match(/^#\s+(.+?)\s*$/m);
  const rawTitle = heading ? heading[1].trim() : file.replace(/\.md$/i, "");

  notes.push({
    id: overview ? "overview" : `part-${part}`,
    file,
    part,
    title: overview ? "Overview" : rawTitle,
    name: overview ? "Overview" : rawTitle.replace(/^\d+\.\s*/, "").trim(),
    content,
  });
}

const output = `// Generated by build-notes.mjs. Edit the .md files, then run: node build-notes.mjs\nwindow.LLM_NOTES = ${JSON.stringify(notes, null, 2)};\n`;

await writeFile(new URL("notes.js", root), output, "utf8");
console.log(`Generated notes.js with ${notes.length} notes.`);
